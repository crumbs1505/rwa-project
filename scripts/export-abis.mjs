// Copies contract ABIs from Hardhat artifacts into frontend/src/abi.ts as
// `as const` arrays so viem can type every contract call.
//   npx hardhat compile && node scripts/export-abis.mjs
import { readFile, writeFile } from "node:fs/promises";

const contracts = {
  RWAToken: "core/RWAToken.sol/RWAToken.json",
  AssetRegistry: "core/AssetRegistry.sol/AssetRegistry.json",
  AssetFactory: "core/AssetFactory.sol/AssetFactory.json",
  YieldDistributor: "finance/YieldDistributor.sol/YieldDistributor.json",
  TokenSale: "finance/TokenSale.sol/TokenSale.json",
  MockUSDC: "finance/MockUSDC.sol/MockUSDC.json",
};

const root = new URL("../", import.meta.url);
let out = "// Generated by scripts/export-abis.mjs — do not edit by hand.\n";

for (const [name, path] of Object.entries(contracts)) {
  const artifact = JSON.parse(
    await readFile(new URL(`artifacts/contracts/${path}`, root), "utf8"),
  );
  out += `\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}

await writeFile(new URL("frontend/src/abi.ts", root), out);
console.log(`Wrote ABIs for ${Object.keys(contracts).join(", ")}`);
